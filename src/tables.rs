//! Numeric tables transcribed **solely** from ISO/IEC 11172-3 (1993)
//! Annex B (3-Annex B "Tables"), the staged 157-page edition.
//!
//! Two tables drive the final Layer I decode stages:
//!
//! * [`SCALEFACTORS`] — Table 3-B.1 "LAYER I, II SCALEFACTORS"
//!   (PDF page 51): the 63 multipliers applied after sample
//!   requantization (§2.4.3.2). Each value is the printed decimal
//!   from the table; the entries follow the closed-form relation
//!   `scalefactor[i] = 2^((3-i)/3)` (the multiplier halves every
//!   three indices: index 0 → 2, index 3 → 1, index 6 → 1/2), which
//!   the unit tests check every printed entry against.
//! * [`SYNTHESIS_WINDOW`] — Table 3-B.3 "COEFFICIENTS Di OF THE
//!   SYNTHESIS WINDOW" (PDF pages 56-58): the 512 window taps Di
//!   used by the polyphase synthesis filterbank (§2.4.3.2, flow
//!   chart 3-Annex A Figure 3-A.2). These coefficients "have been
//!   derived by numerical optimization" (§2.4.3.2) and are not
//!   closed-form; they are transcribed verbatim from the three PDF
//!   table pages.
//!
//! The ISO PDF prints decimals with a comma separator (European
//! convention, e.g. `2,00000000000000`). The transcriptions below
//! use the Rust `.` separator for the same numeric value.

