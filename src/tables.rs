    #[test]
    fn scalefactor_table_matches_formula() {
        // Table 3-B.1: scalefactor[i] = 2^((3 - i) / 3) for the 63
        // standard-defined entries (index 0..=62). Anchor points read
        // from the printed table: index 0 -> 2, index 3 -> 1,
        // index 6 -> 1/2, i.e. the multiplier halves every 3 indices.
        for (i, &printed) in SCALEFACTORS.iter().enumerate().take(63) {
            let expected = 2.0_f64.powf((3.0 - i as f64) / 3.0);
            // The printed decimals carry ~14 significant figures; allow
            // a relative tolerance comfortably wider than the last
            // printed digit.
            let rel = (printed - expected).abs() / expected;
            assert!(
                rel < 5e-9,
                "scalefactor[{i}] printed {printed}, formula {expected}, rel {rel}"
            );
        }
    }

