    #[test]
    fn synthesis_window_endpoints_and_peak() {
        // D[0] is exactly zero (PDF page 56).
        assert_eq!(SYNTHESIS_WINDOW[0], 0.000000000);
        // D[256] is the table's peak magnitude, 1.144989014 (page 57).
        assert_eq!(SYNTHESIS_WINDOW[256], 1.144989014);
        // The first sign flip is at D[64] (negative run ends at D[63]).
        // Index through a runtime binding so the comparison isn't
        // const-folded into a trivially-true assertion.
        let d: &[f64] = &SYNTHESIS_WINDOW;
        assert!(d[63] < 0.0, "D[63] should close the first negative run");
        assert!(d[64] > 0.0, "D[64] should open the first positive run");
        // The last 6 taps are all the quantization step +0.000015259.
        for v in &d[506..512] {
            assert_eq!(*v, 0.000015259);
        }
    }

    #[test]
    fn synthesis_window_quantization_step() {
        // Every tap is a multiple of the 2^-16 quantization step the
        // table is built on (1/65536 = 0.0000152587890625). The printed
        // decimals are rounded to 9 places, so check each entry rounds
        // to an integer multiple within half a printed ulp.
        const STEP: f64 = 1.0 / 65536.0;
        for (i, &d) in SYNTHESIS_WINDOW.iter().enumerate() {
            let n = (d / STEP).round();
            let err = (d - n * STEP).abs();
            assert!(
                err < 6e-10,
                "D[{i}] = {d} is not a clean multiple of 2^-16 (err {err})"
            );
        }
    }

    #[test]
    fn synthesis_window_symmetry() {
        // The matrixing/window construction makes the table symmetric:
        // D[512 - i] == D[i] for i in 1..256 (page-57/56 mirror). The
        // single-sided peak at D[256] has no mirror partner.
        for i in 1..256 {
            assert_eq!(
                SYNTHESIS_WINDOW[512 - i].abs(),
                SYNTHESIS_WINDOW[i].abs(),
                "symmetry broken at i={i}"
            );
        }
    }
