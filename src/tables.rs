    fn synthesis_window_quantization_step() {
        // Every tap is a multiple of the 2^-16 quantization step the
        // table is built on (1/65536 = 0.0000152587890625). The printed
        // decimals are rounded to 9 places, so check each entry rounds
        // to an integer multiple within half a printed ulp.
        const STEP: f64 = 1.0 / 65536.0;
        for (i, &d) in SYNTHESIS_WINDOW.iter().enumerate() {
            let n = (d / STEP).round();
            let err = (d - n * STEP).abs();
            assert!(
                err < 6e-10,
                "D[{i}] = {d} is not a clean multiple of 2^-16 (err {err})"
            );
        }
    }

    #[test]
    fn synthesis_window_symmetry() {
        // The matrixing/window construction makes the table symmetric:
        // D[512 - i] == D[i] for i in 1..256 (page-57/56 mirror). The
        // single-sided peak at D[256] has no mirror partner.
        for i in 1..256 {
            assert_eq!(
                SYNTHESIS_WINDOW[512 - i].abs(),
                SYNTHESIS_WINDOW[i].abs(),
                "symmetry broken at i={i}"
            );
        }
    }

