    #[test]
    fn analysis_window_magnitude_tracks_synthesis() {
        // The analysis and synthesis prototype filters are the same up
        // to a factor of 32: |C[i]| ≈ |D[i]| / 32. Both tables were
        // transcribed independently from their own page renders; this
        // cross-check catches a transcription slip in either table.
        for i in 0..512 {
            let want = SYNTHESIS_WINDOW[i].abs() / 32.0;
            let got = ANALYSIS_WINDOW[i].abs();
            // Each table rounds to its own printed precision, so the
            // ratio can drift by up to ~half an ulp of either table.
            assert!((got - want).abs() < 5e-8, "i={i}: |C|={got}, |D|/32={want}");
        }
    }

    // ---- Table C.2 / C.3 encoder coefficients -----------------

    #[test]
    fn quant_coefficients_closed_form() {
        // Table C.3: A = (2^nb - 1) / 2^nb = steps/(steps+1),
        // B = -1 / 2^nb, for nb in 2..=15. Both follow from the number
        // of steps = 2^nb - 1.
        for nb in 2u32..=15 {
            let two_pow = (1u64 << nb) as f64;
            let want_a = (two_pow - 1.0) / two_pow;
            let want_b = -1.0 / two_pow;
            assert!(
                (QUANT_A[nb as usize] - want_a).abs() < 1e-9,
                "A[nb={nb}] = {}, want {want_a}",
                QUANT_A[nb as usize]
            );
            assert!(
                (QUANT_B[nb as usize] - want_b).abs() < 1e-9,
                "B[nb={nb}] = {}, want {want_b}",
                QUANT_B[nb as usize]
            );
        }
    }

